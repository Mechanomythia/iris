package cloudenv

import (
	"fmt"
	"strings"
)

// SetupScript is the environment's setup script. It runs as root before the
// environment's variables exist, so it only installs tools and the iris
// bootstrap; credentials are materialised at session time by EnvScript,
// which bash sources for every command through BASH_ENV (and login shells
// through /etc/profile.d).
func SetupScript(r Request) string {
	var b strings.Builder
	b.WriteString("#!/bin/bash\n")
	fmt.Fprintf(&b, "# Generated by `iris cloud new` for environment %q.\n", r.Name)
	b.WriteString("# Runs as root before variables and secrets exist: installs tools only.\nset -u\n\n")

	if r.needsGoogle() {
		b.WriteString(`# Google Cloud CLI (apt repo: packages.cloud.google.com is in Allowed domains)
if ! command -v gcloud >/dev/null; then
  (curl -fsSL https://packages.cloud.google.com/apt/doc/apt-key.gpg | gpg --dearmor -o /usr/share/keyrings/cloud.google.gpg \
    && echo "deb [signed-by=/usr/share/keyrings/cloud.google.gpg] https://packages.cloud.google.com/apt cloud-sdk main" > /etc/apt/sources.list.d/google-cloud-sdk.list \
    && apt-get update -qq \
`)
		pkgs := "google-cloud-cli"
		if r.GKE != nil {
			pkgs += " google-cloud-cli-gke-gcloud-auth-plugin kubectl"
		}
		fmt.Fprintf(&b, "    && apt-get install -y -qq %s) || echo \"iris: gcloud install failed\"\nfi\n\n", pkgs)
	}
	if r.AWS != nil {
		b.WriteString(`# AWS CLI v2
if ! command -v aws >/dev/null; then
  (cd /tmp && curl -fsSL "https://awscli.amazonaws.com/awscli-exe-linux-$(uname -m).zip" -o awscliv2.zip \
    && unzip -q -o awscliv2.zip && ./aws/install >/dev/null && rm -rf aws awscliv2.zip) || echo "iris: aws cli install failed"
fi

`)
	}
	if r.Firebase != nil {
		b.WriteString(`# Firebase CLI
command -v firebase >/dev/null || npm install -g --silent firebase-tools || echo "iris: firebase-tools install failed"

`)
	}

	if bootstrapNeeded(r) {
		b.WriteString("# iris bootstrap: turns the environment's variables into logged-in CLIs at session time.\n")
		fmt.Fprintf(&b, "cat > %s <<'IRIS_ENV'\n%sIRIS_ENV\n", EnvScript, envScript(r))
		fmt.Fprintf(&b, "chmod 644 %s\nln -sf %s /etc/profile.d/iris-cloud.sh\n", EnvScript, EnvScript)
		fmt.Fprintf(&b, "cat > /usr/local/bin/iris-cloud-auth <<'IRIS_CHECK'\n%sIRIS_CHECK\nchmod 755 /usr/local/bin/iris-cloud-auth\n", checkScript(r))
	}
	b.WriteString("\nexit 0\n")
	return b.String()
}

// envScript is sourced before every bash command: it must be fast, silent
// and idempotent (marker files), and never print secrets.
func envScript(r Request) string {
	var b strings.Builder
	b.WriteString(`# iris: credentials from environment variables, once per VM. Silent and idempotent.
_iris_dir=/root/.config/iris
`)
	if r.needsGoogle() {
		fmt.Fprintf(&b, `if [ -n "${IRIS_GCP_SA_KEY_B64:-}" ] && [ ! -s %[1]s ]; then
  mkdir -p "$_iris_dir" && (umask 077; printf %%s "$IRIS_GCP_SA_KEY_B64" | base64 -d > %[1]s) 2>/dev/null
fi
`, KeyPath)
	}
	if r.GKE != nil {
		fmt.Fprintf(&b, `if [ -n "${IRIS_GKE_CLUSTER:-}" ] && [ -s %s ] && [ ! -e "$_iris_dir/.gke" ] && command -v gcloud >/dev/null; then
  touch "$_iris_dir/.gke"
  gcloud container clusters get-credentials "$IRIS_GKE_CLUSTER" --location "$IRIS_GKE_LOCATION" --dns-endpoint --quiet >/dev/null 2>&1 || rm -f "$_iris_dir/.gke"
fi
`, KeyPath)
	}
	if r.Registry != nil {
		b.WriteString(`if [ -n "${IRIS_GAR_HOST:-}" ] && [ ! -e "$_iris_dir/.gar" ] && command -v gcloud >/dev/null; then
  touch "$_iris_dir/.gar"; gcloud auth configure-docker "$IRIS_GAR_HOST" --quiet >/dev/null 2>&1 || rm -f "$_iris_dir/.gar"
fi
`)
	}
	if r.Docker != nil {
		b.WriteString(`if [ -n "${IRIS_DOCKER_TOKEN:-}" ] && [ ! -e "$_iris_dir/.docker" ] && command -v docker >/dev/null && docker info >/dev/null 2>&1; then
  printf %s "$IRIS_DOCKER_TOKEN" | docker login "${IRIS_DOCKER_REGISTRY:-docker.io}" -u "$IRIS_DOCKER_USER" --password-stdin >/dev/null 2>&1 && mkdir -p "$_iris_dir" && touch "$_iris_dir/.docker"
fi
`)
	}
	b.WriteString("unset _iris_dir\n")
	return b.String()
}

func checkScript(r Request) string {
	var b strings.Builder
	b.WriteString("#!/bin/bash\n# iris: show which credentials work in this session (never prints secrets).\n")
	fmt.Fprintf(&b, "[ -f %s ] && . %s\n", EnvScript, EnvScript)
	b.WriteString(`ok(){ printf '  ok    %s\n' "$1"; }; bad(){ printf '  FAIL  %s\n' "$1"; }
echo "iris-cloud-auth"
`)
	if r.needsGoogle() {
		fmt.Fprintf(&b, `if [ -s %s ] && gcloud auth print-access-token >/dev/null 2>&1; then ok "gcloud: $(gcloud config get-value account 2>/dev/null)"; else bad "gcloud (IRIS_GCP_SA_KEY_B64 set? packages.cloud.google.com allowed?)"; fi
`, KeyPath)
	}
	if r.GKE != nil {
		b.WriteString(`if kubectl version --request-timeout=10s >/dev/null 2>&1; then ok "kubectl: $(kubectl config current-context)"; else bad "kubectl (DNS endpoint enabled? *.gke.goog allowed?)"; fi
`)
	}
	if r.AWS != nil {
		b.WriteString(`if aws sts get-caller-identity --query Arn --output text >/dev/null 2>&1; then ok "aws: $(aws sts get-caller-identity --query Arn --output text)"; else bad "aws (AWS_ACCESS_KEY_ID set?)"; fi
`)
	}
	if r.Docker != nil {
		b.WriteString(`if [ -e /root/.config/iris/.docker ]; then ok "docker login ${IRIS_DOCKER_REGISTRY:-docker.io}"; else bad "docker login (is dockerd running? start it with: dockerd >/tmp/dockerd.log 2>&1 &)"; fi
`)
	}
	return b.String()
}
