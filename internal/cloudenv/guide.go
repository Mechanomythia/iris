package cloudenv

import (
	"fmt"
	"strings"
)

// Markdown renders the guide with secrets redacted (safe to save and share).
func (g Guide) Markdown() string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Claude Code cloud environment: %s\n\n", g.Name)
	b.WriteString("Generated by `iris cloud new`. There is no API for environments, so add these settings by hand at [claude.ai/code](https://claude.ai/code): on the new-session screen, open the environment selector (the first control under the message box), choose **New environment**, then fill in each row below and select **Add environment**.\n\n")
	if len(g.Warnings) > 0 {
		b.WriteString("## Read first\n\n")
		for _, w := range g.Warnings {
			fmt.Fprintf(&b, "- %s\n", w)
		}
		b.WriteString("\n")
	}
	fmt.Fprintf(&b, "## 1. Name\n\n`%s`\n\n", g.Name)
	pm := "checked"
	if !g.PackageManager {
		pm = "unchecked"
	}
	fmt.Fprintf(&b, "## 2. Network access\n\n**%s**, with **Allow package managers** %s.", g.Network, pm)
	if len(g.AllowedDomains) > 0 {
		b.WriteString(" **Allowed domains**, one per line:\n\n```text\n" + strings.Join(g.AllowedDomains, "\n") + "\n```\n\n")
	} else {
		b.WriteString(" No extra domains needed: the default allowlist covers them.\n\n")
	}
	b.WriteString("## 3. Environment variables\n\n")
	if len(g.EnvVars) == 0 {
		b.WriteString("None.\n\n")
	} else {
		b.WriteString("Paste into **Environment variables** (`.env` format). Secret values are in `secrets.json` next to this file (mode 0600); `iris cloud show " + g.Name + "` copies the full block.\n\n```text\n" + g.RedactedEnvBlock() + "```\n\n")
	}
	b.WriteString("## 4. Network secrets\n\n")
	if len(g.NetSecrets) == 0 {
		b.WriteString("None. (GitHub needs none: the GitHub proxy authenticates attached repositories.)\n\n")
	} else {
		b.WriteString("Select **Network secrets → Add secret** once per row. The proxy adds the header outside the VM, so the token never enters the session.\n\n| Service | Allowed websites | Header name | Prefix | Value |\n| --- | --- | --- | --- | --- |\n")
		for _, s := range g.NetSecrets {
			prefix := s.Prefix
			if prefix == "" {
				prefix = "(clear it)"
			}
			fmt.Fprintf(&b, "| %s | `%s` | `%s` | %s | %s |\n", s.Service, s.Host, s.Header, prefix, s.Value)
		}
		b.WriteString("\n")
	}
	b.WriteString("## 5. Setup script\n\nPaste into **Setup script** (or **Choose file** → `setup.sh` next to this file). It installs tools only; it runs before variables and secrets exist.\n\n```bash\n" + g.SetupScript + "```\n\n")
	b.WriteString("## 6. Start a session\n\n")
	if g.Repositories {
		b.WriteString("Select the repositories Claude should work on when you start the session; the GitHub proxy gives it access to exactly those.\n\n")
	}
	b.WriteString("Paste this as the first message to check everything:\n\n> " + g.FirstSession + "\n")
	return b.String()
}
